def codepoints() -> list:
    """Every character the face can draw, lowercase included, in code order."""
    got = set(_GLYPHS)
    got |= {c.lower() for c in _GLYPHS if c.isalpha()}
    return sorted(ord(c) for c in got)


def rows(char: str) -> list:
    """The seven 5-cell rows for ``char``, falling back to ``?``."""
    glyph = _GLYPHS.get(char) or _GLYPHS.get(char.upper()) or _GLYPHS["?"]
    out = glyph.split()
    if len(out) != HEIGHT or any(len(r) != WIDTH for r in out):
        raise AssertionError("glyph %r is not %dx%d" % (char, WIDTH, HEIGHT))
    return out


def check() -> int:
    """Every glyph is well formed.  Returns the glyph count."""
    for char in _GLYPHS:
        rows(char)
    return len(_GLYPHS)


if __name__ == "__main__":
    print("%d glyphs, %dx%d, all well formed" % (check(), WIDTH, HEIGHT))
